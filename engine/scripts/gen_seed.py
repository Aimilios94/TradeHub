"""Generate supabase/migrations/0002_seed.sql from the Python seed data + prompt-library templates.

Single source of truth:
  - app/registry.py              → plugin_registry rows
  - app/seed/strategies.py       → strategy_configs rows (validated by app/models.py)
  - app/seed/frameworks.py       → frameworks rows
  - app/seed/settings.py         → app_settings rows
  - prompt-library/hermes-core/*.md → prompt_templates rows (header + code blocks parsed here)

Usage (from /engine):  python scripts/gen_seed.py [--check]
  --check  : exit 1 if the on-disk SQL differs from what would be generated (CI / pytest use)
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ENGINE_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ENGINE_ROOT))

from app.models import PromptTemplate  # noqa: E402
from app.registry import ALL_PLUGINS  # noqa: E402
from app.seed.frameworks import all_frameworks  # noqa: E402
from app.seed.settings import APP_SETTINGS  # noqa: E402
from app.seed.strategies import all_strategies  # noqa: E402

REPO_ROOT = ENGINE_ROOT.parent
TEMPLATE_DIR = REPO_ROOT / "prompt-library" / "hermes-core"
OUT_FILE = REPO_ROOT / "supabase" / "migrations" / "0002_seed.sql"

_HEADER_RE = re.compile(r"^---\s*\n(.*?)\n---\s*\n", re.S)
_BLOCK_RE = re.compile(r"^## (?P<title>[^\n]+)\n+```(?P<lang>\w*)\n(?P<body>.*?)\n```", re.S | re.M)
_PURPOSE_RE = re.compile(r"^## Purpose\n(?P<body>.*?)(?=^## )", re.S | re.M)


def sql_str(value) -> str:
    """Quote a Python value as a SQL literal. Uses dollar-quoting for long text so prompts stay readable."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (dict, list)):
        return f"$json${json.dumps(value, ensure_ascii=False, separators=(',', ':'))}$json$::jsonb"
    s = str(value)
    if "\n" in s or "'" in s or len(s) > 80:
        assert "$txt$" not in s, "text contains the dollar-quote tag"
        return f"$txt${s}$txt$"
    return "'" + s.replace("'", "''") + "'"


def sql_jsonb(value) -> str:
    """Always a jsonb literal — needed for scalar values (true/false/numbers/strings) going into jsonb columns."""
    return f"$json${json.dumps(value, ensure_ascii=False, separators=(',', ':'))}$json$::jsonb"


def sql_text_array(values: list[str]) -> str:
    return "array[" + ", ".join(sql_str(v) for v in values) + "]::text[]" if values else "'{}'::text[]"


def load_templates() -> list[PromptTemplate]:
    templates: list[PromptTemplate] = []
    for path in sorted(TEMPLATE_DIR.glob("*.md")):
        text = path.read_text(encoding="utf-8")
        m = _HEADER_RE.match(text)
        if not m:
            raise ValueError(f"{path.name}: missing YAML-style header")
        header = {}
        for line in m.group(1).splitlines():
            k, _, v = line.partition(":")
            header[k.strip()] = v.strip()
        blocks = {b.group("title").strip(): b.group("body") for b in _BLOCK_RE.finditer(text)}
        purpose = _PURPOSE_RE.search(text)
        missing = {"System prompt", "User prompt template", "Output schema"} - set(blocks)
        if missing:
            raise ValueError(f"{path.name}: missing sections {sorted(missing)}")
        templates.append(
            PromptTemplate(
                number=int(header["number"]),
                slug=header["slug"],
                name=header["name"],
                tier=header["tier"],  # type: ignore[arg-type]
                model=header["model"],
                version=int(header.get("version", 1)),
                purpose=(purpose.group("body").strip() if purpose else ""),
                system_prompt=blocks["System prompt"].strip(),
                user_template=blocks["User prompt template"].strip(),
                output_schema=json.loads(blocks["Output schema"]),
                library_file=str(path.relative_to(REPO_ROOT)).replace("\\", "/"),
            )
        )
    numbers = [t.number for t in templates]
    assert numbers == sorted(numbers) and len(set(numbers)) == len(numbers), "template numbers must be unique"
    return templates


def render() -> str:
    templates = load_templates()
    strategies = all_strategies()
    frameworks = all_frameworks()
    out: list[str] = []
    w = out.append

    w("-- ============================================================================")
    w("-- TradeHub — seed data. GENERATED by engine/scripts/gen_seed.py — DO NOT EDIT BY HAND.")
    w("-- Sources: app/registry.py, app/seed/*.py, prompt-library/hermes-core/*.md")
    w(f"-- Counts: {len(ALL_PLUGINS)} plugins, {len(strategies)} strategies, {len(frameworks)} frameworks, "
      f"{len(templates)} prompt templates, {len(APP_SETTINGS)} settings")
    w("-- ============================================================================")
    w("")
    w("begin;")
    w("")

    w("-- ---------------------------------------------------------------- app_settings")
    for key, row in APP_SETTINGS.items():
        w(f"insert into app_settings (key, value, description) values ({sql_str(key)}, {sql_jsonb(row['value'])}, "
          f"{sql_str(row['description'])})\n  on conflict (key) do update set value = excluded.value, description = excluded.description;")
    w("")

    w("-- ---------------------------------------------------------------- plugin_registry")
    for p in ALL_PLUGINS:
        w(f"insert into plugin_registry (name, kind, number, description, params, status, notes) values "
          f"({sql_str(p['name'])}, {sql_str(p['kind'])}, {p['number']}, {sql_str(p['description'])}, "
          f"{sql_str(p['params'])}, {sql_str(p['status'])}, {sql_str(p['notes'] or None)})\n"
          f"  on conflict (name) do update set kind = excluded.kind, number = excluded.number, description = excluded.description, "
          f"params = excluded.params, status = excluded.status, notes = excluded.notes;")
    w("")

    w("-- ---------------------------------------------------------------- frameworks")
    for f in frameworks:
        w(f"insert into frameworks (code, name, creator, description, rules, library_file) values "
          f"({sql_str(f.code)}, {sql_str(f.name)}, {sql_str(f.creator)}, {sql_str(f.description)}, "
          f"{sql_str(f.rules)}, {sql_str(f.library_file)})\n"
          f"  on conflict (code) do update set name = excluded.name, creator = excluded.creator, description = excluded.description, "
          f"rules = excluded.rules, library_file = excluded.library_file;")
    w("")

    w("-- ---------------------------------------------------------------- prompt_templates")
    for t in templates:
        w(f"insert into prompt_templates (number, slug, name, tier, model, version, purpose, system_prompt, user_template, "
          f"output_schema, library_file, active) values\n"
          f"  ({t.number}, {sql_str(t.slug)}, {sql_str(t.name)}, {sql_str(t.tier)}, {sql_str(t.model)}, {t.version}, "
          f"{sql_str(t.purpose)},\n  {sql_str(t.system_prompt)},\n  {sql_str(t.user_template)},\n  {sql_str(t.output_schema)}, "
          f"{sql_str(t.library_file)}, {sql_str(t.active)})\n"
          f"  on conflict (slug) do update set number = excluded.number, name = excluded.name, tier = excluded.tier, model = excluded.model, "
          f"version = excluded.version, purpose = excluded.purpose, system_prompt = excluded.system_prompt, "
          f"user_template = excluded.user_template, output_schema = excluded.output_schema, library_file = excluded.library_file, "
          f"active = excluded.active;")
    w("")

    w("-- ---------------------------------------------------------------- strategy_configs")
    slugs = {t.slug for t in templates}
    for s in strategies:
        if s.prompt_template_slug and s.prompt_template_slug not in slugs:
            raise ValueError(f"{s.code}: unknown prompt_template_slug {s.prompt_template_slug}")
        tpl = (f"(select id from prompt_templates where slug = {sql_str(s.prompt_template_slug)})"
               if s.prompt_template_slug else "null")
        w(f"insert into strategy_configs (code, name, creator, provenance, style, timeframe, automation_mode, status, instruments, "
          f"frameworks, universe, entry_conditions, exit_logic, risk, reentry, prompt_template_id, library_file, notes) values\n"
          f"  ({sql_str(s.code)}, {sql_str(s.name)}, {sql_str(s.creator)}, {sql_str(s.provenance.value)}, {sql_str(s.style.value)}, "
          f"{sql_str(s.timeframe)}, {sql_str(s.automation_mode.value)}, {sql_str(s.status.value)}, {sql_str(s.instruments)},\n"
          f"  {sql_text_array(list(s.frameworks))},\n"
          f"  {sql_str(s.universe.model_dump(mode='json'))},\n"
          f"  {sql_str(s.entry_conditions.model_dump(mode='json', exclude_none=True))},\n"
          f"  {sql_str([e.model_dump(mode='json', exclude_none=True) for e in s.exit_logic])},\n"
          f"  {sql_str(s.risk.model_dump(mode='json', exclude_none=True))},\n"
          f"  {sql_str(s.reentry.model_dump(mode='json'))},\n"
          f"  {tpl}, {sql_str(s.library_file)}, {sql_str(s.notes)})\n"
          f"  on conflict (code) do update set name = excluded.name, creator = excluded.creator, provenance = excluded.provenance, "
          f"style = excluded.style, timeframe = excluded.timeframe, automation_mode = excluded.automation_mode, "
          f"instruments = excluded.instruments, frameworks = excluded.frameworks, universe = excluded.universe, "
          f"entry_conditions = excluded.entry_conditions, exit_logic = excluded.exit_logic, risk = excluded.risk, "
          f"reentry = excluded.reentry, prompt_template_id = excluded.prompt_template_id, library_file = excluded.library_file, "
          f"notes = excluded.notes;  -- status intentionally NOT overwritten on re-seed")
    w("")
    w("commit;")
    w("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    sql = render()
    if "--check" in argv:
        current = OUT_FILE.read_text(encoding="utf-8") if OUT_FILE.exists() else ""
        if current != sql:
            print(f"{OUT_FILE} is out of date — run: python scripts/gen_seed.py")
            return 1
        print("seed SQL up to date")
        return 0
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(sql, encoding="utf-8", newline="\n")
    print(f"wrote {OUT_FILE} ({len(sql):,} chars)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
